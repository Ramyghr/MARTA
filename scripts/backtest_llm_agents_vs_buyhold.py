"""One-off backtest: LLM-agent-consensus rule-based strategy vs buy-and-hold, BTC_USDT 2024 val.

Uses the dense debate cache built via the Kaggle debate-coverage run
(kaggle_debate_coverage_instructions.md, 2026-09-02) — 384 real debates, now covering
~94% of the BTC 2024 validation window (up from ~1%). Every debate was generated by
run_debate.py's normal DebateGraph, which injects full RegimeContext (regime label +
probability vector) into every agent's LLM prompt — so this consensus is "LLM agents
WITH regime" by construction. There is no companion "without regime" cache from this
same run; that would need a separate generation pass via run_clean_ablation_debates.py's
include_regime=False path (see rl/ablation.py's _NO_REGIME_DEBATE_PATH /
data/debates/debate_results_no_regime.json).

No PPO involved — reuses rl/ablation.py's _run_agents_rule(), the same rule-based sizing
logic as the project's "agents_no_regime" ablation variant, just pointed at the real
(regime-informed) debate cache instead of that variant's dedicated no-regime cache.

Run: /home/ramy/miniconda3/envs/marta/bin/python scripts/backtest_llm_agents_vs_buyhold.py
"""

from __future__ import annotations

import json
from pathlib import Path

import torch

from rl.ablation import _run_agents_rule, _run_buy_hold, bootstrap_sharpe_ci
from rl.evaluate import _periods_per_year_for_env, compute_metrics
from rl.train import build_env_factory, load_data, load_debate_results

_OUTPUT_PATH = Path("data/results/llm_agents_only_backtest.json")


def main() -> None:
    device = "cuda" if torch.cuda.is_available() else "cpu"
    config = {
        "all_assets": ["BTC_USDT", "ETH_USDT", "EURUSD", "GOLD"],
        "device": device,
        "initial_capital": 10_000.0,
        "window_size": 60,
        "transaction_cost": 0.001,
        "lambda_drawdown": 0.01,
        "max_leverage": 1.0,
        "max_episode_steps": 2000,
        "min_hold_bars": 4,
        "min_hold_stop_loss_dd": 0.05,
        "max_drawdown_termination": 0.20,
        "benchmark_relative": False,
    }

    aligned_dfs, regime_stream_df, encoder = load_data(config)
    debate_results = load_debate_results()
    print(f"Loaded {len(debate_results)} cached debates")

    env_factory = build_env_factory(aligned_dfs, regime_stream_df, encoder, debate_results, config)

    bh_env = env_factory(assets=["BTC_USDT"], split="val", sequential=True, debate=False)
    bh_traj = _run_buy_hold(bh_env)
    bh_metrics = compute_metrics(
        bh_traj["returns"], bh_traj["portfolio_values"], bh_traj["positions"],
        periods_per_year=_periods_per_year_for_env(bh_env),
    )

    agent_env = env_factory(assets=["BTC_USDT"], split="val", sequential=True, debate=True)
    agent_traj = _run_agents_rule(agent_env)
    agent_metrics = compute_metrics(
        agent_traj["returns"], agent_traj["portfolio_values"], agent_traj["positions"],
        periods_per_year=_periods_per_year_for_env(agent_env),
    )

    delta, lo, hi = bootstrap_sharpe_ci(agent_traj["returns"], bh_traj["returns"], n_bootstrap=1000)
    significant = lo > 0 or hi < 0

    n_steps_matched = sum(
        1 for i in range(len(agent_traj["positions"])) if abs(agent_traj["positions"][i]) > 1e-6
    )

    result = {
        "buy_hold": bh_metrics,
        "llm_agents_with_regime": agent_metrics,
        "bootstrap_delta_sharpe_llm_agents_vs_buy_hold": {
            "delta": delta, "ci_lower_95": lo, "ci_upper_95": hi, "significant": significant,
        },
        "n_debates_in_cache": len(debate_results),
        "n_val_steps_with_nonzero_position": n_steps_matched,
        "n_val_steps_total": len(agent_traj["positions"]),
        "note": (
            "llm_agents_with_regime uses rl/ablation.py's _run_agents_rule() (nearest cached "
            "debate within 7 days drives direction/size, no PPO) against data/debates/"
            "debate_results.json. Every debate in that cache was generated with full "
            "RegimeContext injected into agent prompts, so this already IS the "
            "regime-conditioned variant. No 'without regime' counterpart exists from this "
            "cache — that requires a separate generation pass "
            "(run_clean_ablation_debates.py, include_regime=False)."
        ),
    }

    _OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    _OUTPUT_PATH.write_text(json.dumps(result, indent=2, default=float))
    print(json.dumps(result, indent=2, default=float))


if __name__ == "__main__":
    main()
