"""Ablation study: 7 system variants + bootstrap CIs on Sharpe deltas.

This is the central research result — it isolates the contribution of (a) the regime
embedding, (b) the multi-agent consensus, and (c) the PPO execution layer, and compares
against two recognizable rule-based trading baselines (RSI mean-reversion, MA crossover).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Callable

import numpy as np
import pandas as pd
from stable_baselines3.common.base_class import BaseAlgorithm

from rl.env import MARTATradingEnv
from rl.evaluate import compute_metrics, run_walk_forward
from utils.logger import logger

_RESULTS_PATH = Path("data/results/ablation_results.json")
_NO_REGIME_DEBATE_PATH = Path("data/debates/debate_results_no_regime.json")
_ANNUALIZE = np.sqrt(24 * 365)

# regime / agents / ppo switches per variant.
ABLATION_VARIANTS: dict[str, dict[str, Any]] = {
    "buy_hold": {"regime": False, "agents": False, "ppo": False},
    "rsi_strategy": {"regime": False, "agents": False, "ppo": False, "strategy": "rsi"},
    "ma_crossover": {"regime": False, "agents": False, "ppo": False, "strategy": "ma"},
    "ppo_no_regime": {"regime": False, "agents": False, "ppo": True},
    "agents_no_regime": {"regime": False, "agents": True, "ppo": False},
    "ppo_agents_no_regime": {"regime": False, "agents": True, "ppo": True},
    "marta_full": {"regime": True, "agents": True, "ppo": True},
}

_DIRECTION_FROM_ACTION = {"long": 0, "short": 1, "hold": 2}

_MOMENTUM_LOOKBACK = 3
_MOMENTUM_POSITION_FRACTION = 0.3
_NEAREST_DEBATE_MAX_DAYS = 7

_RSI_PERIOD = 14
_RSI_OVERBOUGHT = 70.0
_RSI_OVERSOLD = 30.0
_MA_FAST = 12
_MA_SLOW = 26
_RULE_POSITION_SIZE = 0.3  # same fixed size as the momentum baseline


def _sharpe(returns: np.ndarray) -> float:
    if len(returns) < 2:
        return 0.0
    return float(returns.mean() / (returns.std() + 1e-8) * _ANNUALIZE)


def bootstrap_sharpe_ci(
    returns_a: np.ndarray,
    returns_b: np.ndarray,
    n_bootstrap: int = 1000,
    block_size: int = 168,
) -> tuple[float, float, float]:
    """
    Block bootstrap CI on Sharpe ratio delta.
    Uses non-overlapping blocks of `block_size` to preserve autocorrelation structure.
    Returns (delta_sharpe, ci_lower_95, ci_upper_95).
    """
    returns_a = np.asarray(returns_a, dtype=np.float64)
    returns_b = np.asarray(returns_b, dtype=np.float64)
    n = min(len(returns_a), len(returns_b))
    n_blocks = n // block_size

    # Too few complete blocks to resample — fall back to a zero-width CI at the point delta.
    if n_blocks < 2:
        delta = _sharpe(returns_a[:n]) - _sharpe(returns_b[:n])
        return float(delta), float(delta), float(delta)

    # Trim to complete blocks
    returns_a = returns_a[:n_blocks * block_size].reshape(n_blocks, block_size)
    returns_b = returns_b[:n_blocks * block_size].reshape(n_blocks, block_size)

    deltas = []
    rng = np.random.default_rng(42)
    for _ in range(n_bootstrap):
        idx = rng.integers(0, n_blocks, size=n_blocks)
        sample_a = returns_a[idx].ravel()
        sample_b = returns_b[idx].ravel()
        sharpe_a = sample_a.mean() / (sample_a.std() + 1e-8) * np.sqrt(24 * 365)
        sharpe_b = sample_b.mean() / (sample_b.std() + 1e-8) * np.sqrt(24 * 365)
        deltas.append(sharpe_a - sharpe_b)

    deltas = np.array(deltas)
    delta = float(np.mean(deltas))
    ci_lower = float(np.percentile(deltas, 2.5))
    ci_upper = float(np.percentile(deltas, 97.5))
    return delta, ci_lower, ci_upper


def _load_no_regime_debates() -> list[dict] | None:
    """Debate cache generated by run_clean_ablation_debates.py — agents deliberated with
    serialize_context_for_prompt(include_regime=False), so they never saw the regime label,
    description, or probability vector. Distinct from the main (regime-informed) debate cache.
    """
    if not _NO_REGIME_DEBATE_PATH.exists():
        logger.warning(
            f"{_NO_REGIME_DEBATE_PATH} not found — run `python run_clean_ablation_debates.py` "
            "first; agents_no_regime will fall back to an empty consensus (all-hold)"
        )
        return None
    return json.loads(_NO_REGIME_DEBATE_PATH.read_text())


def _run_buy_hold(env: MARTATradingEnv) -> dict[str, np.ndarray]:
    """Buy-and-hold BTC over the env's (validation) window."""
    asset = "BTC_USDT"
    starts = env._valid_starts[asset]
    if len(starts) == 0:
        return {"returns": np.array([]), "portfolio_values": np.array([env.initial_capital]),
                "positions": np.array([1.0]), "regimes": np.array([-1])}
    t0, t1 = int(starts[0]), int(starts[-1]) + 1
    r = np.nan_to_num(env._returns[asset][t0 + 1 : t1 + 1])
    pv = env.initial_capital * np.cumprod(1.0 + r)
    pv = np.concatenate([[env.initial_capital], pv])
    regimes = env._regime_labels[asset][t0 : t1 + 1]
    return {
        "returns": r,
        "portfolio_values": pv,
        "positions": np.ones(len(pv)),
        "regimes": regimes,
    }


def _reconstruct_prices(close_returns: np.ndarray) -> np.ndarray:
    """Rebuild a (relative) price series from ``close_return`` log returns."""
    return np.exp(np.cumsum(np.nan_to_num(close_returns)))


def _wilder_rsi(prices: np.ndarray, period: int = _RSI_PERIOD) -> np.ndarray:
    """Classic Wilder RSI (0–100) from a price series.

    NOTE: the ``rsi`` column in the aligned parquet is a rolling 720h z-score (range
    ~±4), so the classic 30/70 thresholds are meaningless on it — the raw RSI must be
    recomputed from prices reconstructed from ``close_return``.
    """
    s = pd.Series(prices)
    delta = s.diff()
    gain = delta.clip(lower=0.0)
    loss = -delta.clip(upper=0.0)
    avg_gain = gain.ewm(alpha=1.0 / period, min_periods=period, adjust=False).mean()
    avg_loss = loss.ewm(alpha=1.0 / period, min_periods=period, adjust=False).mean()
    rs = avg_gain / avg_loss.replace(0.0, np.nan)
    rsi = 100.0 - 100.0 / (1.0 + rs)
    # Warmup / zero-loss stretches → neutral 50 (rule holds there).
    return rsi.fillna(50.0).to_numpy(dtype=np.float64)


def rsi_strategy(
    close_returns: np.ndarray,
    overbought: float = _RSI_OVERBOUGHT,
    oversold: float = _RSI_OVERSOLD,
    position_size: float = _RULE_POSITION_SIZE,
) -> np.ndarray:
    """Classic RSI mean-reversion positions: long below ``oversold``, short above
    ``overbought``, else flat. Position at step ``i`` is decided from RSI at ``i-1``
    (no lookahead) and applies to the return realised at ``i``.
    """
    rsi_values = _wilder_rsi(_reconstruct_prices(close_returns))
    positions = np.zeros(len(close_returns), dtype=np.float64)
    for i in range(1, len(close_returns)):
        if rsi_values[i - 1] < oversold:
            positions[i] = position_size
        elif rsi_values[i - 1] > overbought:
            positions[i] = -position_size
    return positions


def ma_crossover_strategy(
    close_returns: np.ndarray,
    fast: int = _MA_FAST,
    slow: int = _MA_SLOW,
    position_size: float = _RULE_POSITION_SIZE,
) -> np.ndarray:
    """Simple MA crossover positions: long while the fast MA is above the slow MA,
    short otherwise; flat during the ``slow``-bar warmup. Position at step ``i`` is
    decided from MAs at ``i-1`` (no lookahead) and applies to the return at ``i``.
    """
    prices = pd.Series(_reconstruct_prices(close_returns))
    fast_ma = prices.rolling(fast).mean().to_numpy()
    slow_ma = prices.rolling(slow).mean().to_numpy()
    positions = np.zeros(len(close_returns), dtype=np.float64)
    for i in range(slow, len(close_returns)):
        positions[i] = position_size if fast_ma[i - 1] > slow_ma[i - 1] else -position_size
    return positions


def _run_rule_positions(
    env: MARTATradingEnv,
    positions_fn: Callable[[np.ndarray], np.ndarray],
    asset: str = "BTC_USDT",
) -> dict[str, np.ndarray]:
    """Apply a position-array rule over the env's active window (its ``_valid_starts``)
    with the env's transaction cost:

        portfolio_return[t] = position[t] * close_return[t]
                              − transaction_cost * |position[t] − position[t−1]|
    """
    starts = env._valid_starts[asset]
    if len(starts) == 0:
        return {"returns": np.array([]), "portfolio_values": np.array([env.initial_capital]),
                "positions": np.array([0.0]), "regimes": np.array([-1])}
    t0, t1 = int(starts[0]), int(starts[-1]) + 1
    r = np.nan_to_num(env._returns[asset][t0 + 1 : t1 + 1])
    positions = positions_fn(r)
    turnover = np.abs(np.diff(np.concatenate([[0.0], positions])))
    port_r = positions * r - env.transaction_cost * turnover
    pv = env.initial_capital * np.cumprod(1.0 + port_r)
    pv = np.concatenate([[env.initial_capital], pv])
    regimes = env._regime_labels[asset][t0 : t1 + 1]
    return {
        "returns": port_r,
        "portfolio_values": pv,
        "positions": np.concatenate([[0.0], positions]),
        "regimes": regimes,
    }


def _make_nearest_consensus_fn(
    env: MARTATradingEnv, asset: str, max_days: int = _NEAREST_DEBATE_MAX_DAYS
) -> Callable[[pd.Timestamp], np.ndarray | None]:
    """Build a nearest-neighbour lookup from timestamp → consensus vector for ``asset``.

    The debate cache only has ~33 timestamps spread across ~6,500 validation steps, so an
    exact-timestamp match (the old behaviour) defaults to hold ~99.5% of the time. Snapping
    each step to its nearest cached debate (within ``max_days``) gives a real signal on every
    step instead.
    """
    entries = sorted(
        (ts, vec) for (a, ts), vec in env._consensus_lookup.items() if a == asset
    )
    if not entries:
        return lambda ts: None

    timestamps = pd.DatetimeIndex([e[0] for e in entries])
    vecs = np.stack([e[1] for e in entries])
    max_delta = pd.Timedelta(days=max_days)

    def lookup(ts: pd.Timestamp) -> np.ndarray | None:
        pos = int(timestamps.searchsorted(ts))
        candidates = [i for i in (pos - 1, pos) if 0 <= i < len(timestamps)]
        if not candidates:
            return None
        best = min(candidates, key=lambda i: abs(timestamps[i] - ts))
        if abs(timestamps[best] - ts) > max_delta:
            return None
        return vecs[best]

    return lookup


def _run_agents_rule(env: MARTATradingEnv) -> dict[str, np.ndarray]:
    """Rule-based agent baseline: nearest cached debate result (within 7 days) drives
    direction/size on every step. No PPO, no regime conditioning.
    """
    obs, info = env.reset()
    asset = env._asset
    consensus_fn = _make_nearest_consensus_fn(env, asset)
    pv = [info["portfolio_value"]]
    positions = [info["signed_position"]]
    regimes = [info["current_regime"]]
    returns: list[float] = []

    done = False
    while not done:
        ts = env._index[asset][env._t]
        vec = consensus_fn(ts)
        if vec is not None and abs(vec[5]) > 1e-6:
            direction = 0 if vec[5] > 0 else 1  # fm signed conviction sign
            # Cap at 0.05 — the fixed 0.5 fallback otherwise dwarfs the trained PPO's
            # risk-capped sizing (avg position ~0.001-0.006) and inflates Sharpe/return
            # in a way that isn't a fair regime-vs-no-regime comparison.
            raw_frac = abs(vec[6]) if vec[6] > 0 else 0.5
            frac = float(np.clip(min(raw_frac, 0.05), 0.01, 0.99))
            action = np.array([float(direction), frac], dtype=np.float32)
        else:
            action = np.array([2.0, 0.01], dtype=np.float32)  # hold
        obs, reward, terminated, truncated, info = env.step(action)
        pv.append(info["portfolio_value"])
        positions.append(info["signed_position"])
        regimes.append(info["current_regime"])
        returns.append(info["pnl_return"])
        done = terminated or truncated

    return {
        "returns": np.asarray(returns),
        "portfolio_values": np.asarray(pv),
        "positions": np.asarray(positions),
        "regimes": np.asarray(regimes),
    }


def _run_momentum_rule(
    env: MARTATradingEnv, consensus_weighted: bool = False
) -> dict[str, np.ndarray]:
    """Momentum baseline: long when the last 3 close_returns are all positive, short when
    all negative, hold otherwise. Fixed 0.3 position size (scaled by nearest-debate
    confidence when ``consensus_weighted``).

    Stands in for the trained PPO on the no-regime variants: zeroing the regime embedding
    pushes the frozen policy out-of-distribution and it collapses to hold on every step
    (see ``ABLATION_VARIANTS`` docstring / CLAUDE.md). This rule represents "RL-like
    execution without regime awareness" instead of a degenerate all-zero PPO run.
    """
    obs, info = env.reset()
    asset = env._asset
    consensus_fn = _make_nearest_consensus_fn(env, asset) if consensus_weighted else None
    pv = [info["portfolio_value"]]
    positions = [info["signed_position"]]
    regimes = [info["current_regime"]]
    returns: list[float] = []

    done = False
    while not done:
        t = env._t
        window = env._returns[asset][max(0, t - _MOMENTUM_LOOKBACK + 1) : t + 1]
        if len(window) == _MOMENTUM_LOOKBACK and np.all(window > 0):
            direction = 0
        elif len(window) == _MOMENTUM_LOOKBACK and np.all(window < 0):
            direction = 1
        else:
            direction = 2

        frac = _MOMENTUM_POSITION_FRACTION
        if consensus_fn is not None:
            vec = consensus_fn(env._index[asset][t])
            conf = float(abs(vec[5])) if vec is not None else 0.0
            frac = float(np.clip(_MOMENTUM_POSITION_FRACTION * (0.5 + conf), 0.01, 0.99))

        action = np.array([float(direction), frac], dtype=np.float32)
        obs, reward, terminated, truncated, info = env.step(action)
        pv.append(info["portfolio_value"])
        positions.append(info["signed_position"])
        regimes.append(info["current_regime"])
        returns.append(info["pnl_return"])
        done = terminated or truncated

    return {
        "returns": np.asarray(returns),
        "portfolio_values": np.asarray(pv),
        "positions": np.asarray(positions),
        "regimes": np.asarray(regimes),
    }


def run_variant(
    name: str,
    variant_config: dict[str, Any],
    env_factory: Callable[..., MARTATradingEnv],
    model: BaseAlgorithm | None,
) -> dict[str, Any]:
    """Run a single ablation variant on the validation set and return metrics + returns.

    ``ppo_no_regime``, ``agents_no_regime``, and ``ppo_agents_no_regime`` do not invoke the
    trained PPO: zeroing the regime embedding pushes it out-of-distribution and it collapses
    to hold on every step (Sharpe/return/n_trades all exactly 0.0), which reads as "identical
    to hold" rather than "policy collapses without regime context". Each gets a
    non-PPO stand-in baseline instead — see the docstrings of ``_run_momentum_rule`` /
    ``_run_agents_rule`` for what each one actually does.
    """
    logger.info(f"[ablation] running variant '{name}' {variant_config}")

    if name == "buy_hold":
        env = env_factory(assets=["BTC_USDT"], split="val", sequential=True, debate=False)
        traj = _run_buy_hold(env)
        method = "buy-and-hold BTC over the validation window"
    elif name == "rsi_strategy":
        env = env_factory(assets=["BTC_USDT"], split="val", sequential=True, debate=False)
        traj = _run_rule_positions(env, rsi_strategy)
        method = (
            "Classic RSI mean-reversion (buy <30, sell >70, fixed 0.3 size) — raw Wilder "
            "RSI(14) recomputed from close_return (aligned `rsi` column is z-scored)"
        )
    elif name == "ma_crossover":
        env = env_factory(assets=["BTC_USDT"], split="val", sequential=True, debate=False)
        traj = _run_rule_positions(env, ma_crossover_strategy)
        method = (
            "MA crossover (12h fast / 26h slow, long above / short below, fixed 0.3 size, "
            "26-bar warmup hold)"
        )
    elif name == "agents_no_regime":
        env = env_factory(
            assets=["BTC_USDT"], split="val", sequential=True,
            zero_regime=True, debate=_load_no_regime_debates(),
        )
        traj = _run_agents_rule(env)
        method = (
            "LLM agents debated without regime context — clean no-regime baseline. "
            "Nearest cached debate (≤ 7-day lookup) drives direction/size — no PPO."
        )
    elif name == "ppo_no_regime":
        env = env_factory(
            assets=["BTC_USDT"], split="val", sequential=True,
            zero_regime=True, zero_consensus=True, debate=False,
        )
        traj = _run_momentum_rule(env)
        method = (
            "momentum rule (close_return sign, 3-step lookback, fixed 0.3 size) — "
            "PPO collapses to hold without the regime embedding"
        )
    elif name == "ppo_agents_no_regime":
        env = env_factory(
            assets=["BTC_USDT"], split="val", sequential=True,
            zero_regime=True, zero_consensus=False, debate=True,
        )
        traj = _run_momentum_rule(env, consensus_weighted=True)
        method = (
            "momentum rule weighted by nearest cached debate confidence (≤ 7-day "
            "lookup) — PPO collapses to hold without the regime embedding"
        )
    else:  # marta_full
        env = env_factory(
            assets=["BTC_USDT"], split="val", sequential=True,
            zero_regime=False, zero_consensus=False, debate=True,
        )
        traj = run_walk_forward(model, env, deterministic=True)
        method = "trained PPO policy — full regime embedding + agent-consensus conditioning"

    metrics = compute_metrics(traj["returns"], traj["portfolio_values"], traj["positions"])
    metrics["method"] = method
    return {"metrics": metrics, "returns": traj["returns"]}


def run_ablation(
    config: dict,
    model: BaseAlgorithm,
    env_factory: Callable[..., MARTATradingEnv],
) -> dict[str, Any]:
    """Run all 7 variants and bootstrap Sharpe CIs of MARTA-full vs each baseline."""
    variant_results: dict[str, Any] = {}
    returns_by_variant: dict[str, np.ndarray] = {}

    for name, vcfg in ABLATION_VARIANTS.items():
        res = run_variant(name, vcfg, env_factory, model)
        variant_results[name] = res["metrics"]
        returns_by_variant[name] = res["returns"]

    ref = returns_by_variant.get("marta_full", np.array([]))
    bootstrap: dict[str, dict[str, float]] = {}
    n_boot = config.get("n_bootstrap", 1000)
    for name in ABLATION_VARIANTS:
        if name == "marta_full":
            continue
        delta, lo, hi = bootstrap_sharpe_ci(ref, returns_by_variant[name], n_bootstrap=n_boot)
        significant = lo > 0 or hi < 0
        bootstrap[f"marta_full_vs_{name}"] = {
            "delta_sharpe": delta,
            "ci_lower_95": lo,
            "ci_upper_95": hi,
            "significant": bool(significant),
        }

    result = {"variants": variant_results, "bootstrap_ci": bootstrap}
    _RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    _RESULTS_PATH.write_text(json.dumps(result, indent=2, default=float))
    logger.success(f"Ablation results written to {_RESULTS_PATH}")
    return result
