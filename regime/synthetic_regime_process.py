"""Synthetic regime-switching process — calibrated directly from the real, already-fitted
crypto5_multihorizon HMM checkpoint (regime/checkpoints/crypto5_multihorizon/hmm_model.pkl's
transition matrix + per-regime annualized return/vol from
data/validated/regime_semantics_crypto5_multihorizon.json, 2026-08-20 regime-layer audit).

Generates synthetic hourly price paths with a KNOWN ground-truth regime label at every
timestep, via two independent discretization methods, so regime/monte_carlo_regime_
recovery.py can test whether the ACTUAL feature+HMM pipeline (pipeline/features.py +
pipeline/normalize.py + regime/hmm.py) recovers ground truth from data generated by a
process matching what the real HMM believes the world looks like — a question every
other test in this audit implicitly assumed the answer to but never checked.

  1. SDE simulation (level-space Markov-modulated GBM, dS = mu(r_t) S dt + sigma(r_t) S dW):
     both Euler-Maruyama and Milstein schemes, plus an empirical convergence-order check
     (Milstein should show ~O(dt) strong error vs Euler-Maruyama's ~O(sqrt(dt)) — standard
     SDE numerical theory, checked empirically rather than assumed) against the closed-form
     lognormal solution on a regime-held-fixed sub-study.
  2. Regime-switching trinomial tree — CRR-style fixed jump sizes per regime, with the
     three jump PROBABILITIES solved via scipy.optimize (a genuine, if small, calibration
     problem: match target mean and variance subject to summing to 1) rather than a
     textbook closed-form shortcut — an independent, non-SDE discretization method, so
     recovery-test results aren't an artifact of one simulation scheme.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from scipy.optimize import minimize
from scipy.stats import lognorm

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

HOURS_PER_YEAR = 24 * 365
DT = 1.0 / HOURS_PER_YEAR  # one hour, in years
N_STATES = 6

# Calibrated from the real, deployed crypto5_multihorizon checkpoint (2026-08-20).
TRANSMAT = np.array([
    [0.94957, 0.00560, 0.00624, 0.03725, 0.00009, 0.00125],
    [0.00353, 0.93810, 0.00946, 0.03058, 0.01432, 0.00402],
    [0.00513, 0.00637, 0.94994, 0.01590, 0.02124, 0.00142],
    [0.02950, 0.02705, 0.00816, 0.93240, 0.00085, 0.00205],
    [0.00007, 0.01397, 0.02639, 0.00006, 0.94666, 0.01285],
    [0.00074, 0.00425, 0.00175, 0.00000, 0.03717, 0.95608],
])
ANNUAL_LOGRET_MEAN = np.array([-0.3479, 0.7444, -0.1473, -0.1243, 1.4062, -0.8265])
ANNUAL_VOL = np.array([0.3351, 0.6702, 0.6835, 0.4691, 1.0148, 1.8977])
STATIONARY = np.array([0.1523, 0.1724, 0.1878, 0.2026, 0.1945, 0.0904])  # time_pct, empirical

# Per-hour parameters. LOGRET_MEAN_STEP is the empirically-calibrated target — the mean of
# close_return (log return) per hour within regime r. MU_STEP is the corresponding
# level-space GBM drift (Ito correction: E[d log S] = (mu - 0.5 sigma^2) dt).
LOGRET_MEAN_STEP = ANNUAL_LOGRET_MEAN * DT
SIGMA_STEP = ANNUAL_VOL * np.sqrt(DT)
MU_STEP = LOGRET_MEAN_STEP + 0.5 * SIGMA_STEP ** 2


def simulate_regime_path(n_steps: int, rng: np.random.Generator, start_state: int | None = None) -> np.ndarray:
    """Discrete-time Markov chain sample from the real fitted TRANSMAT."""
    states = np.empty(n_steps, dtype=int)
    states[0] = start_state if start_state is not None else rng.choice(N_STATES, p=STATIONARY)
    cum = TRANSMAT.cumsum(axis=1)
    cum[:, -1] = 1.0  # rows should sum to exactly 1; floating-point drift can leave the
    # last cumulative value at e.g. 0.999999997, which searchsorted then pushes one past
    # the last valid state index for the (rare) u values that land in that gap
    u = rng.random(n_steps - 1)
    for t in range(1, n_steps):
        states[t] = np.searchsorted(cum[states[t - 1]], u[t - 1])
    return states


def simulate_correlated_regime_paths(
    n_assets: int, n_steps: int, correlation: float, rng: np.random.Generator,
) -> np.ndarray:
    """H1 test (2026-08-20): n_assets regime paths that co-move the way real
    BTC/ETH/BNB/LTC/XRP volatility states do -- most of the time, a big move in one
    asset's regime shows up in the others too, around the same hour.

    First attempt (kept in git history, not used here) drove each asset's OWN
    TRANSMAT-based chain with correlated Gaussian-copula uniforms. That barely worked:
    simultaneous same-regime fraction came out at 0.8%, because copula-correlating the
    quantile of a transition draw only correlates WHETHER a switch happens, not WHICH
    state it lands in, once assets have already drifted into different previous
    states (which happens fast given independent starts and ~93-96% self-persistence).

    This version is more direct: a shared latent market regime M_t evolves via the
    real TRANSMAT; each asset's OWN regime "snaps" to M_t with probability
    `correlation` each hour, otherwise persists in its own prior state. `correlation`
    directly controls the (measurable, reported) simultaneous same-regime fraction,
    rather than an indirect copula parameter whose effect on that fraction wasn't
    controllable or even sign-obvious in advance."""
    market = simulate_regime_path(n_steps, rng)
    states = np.empty((n_steps, n_assets), dtype=int)
    states[0] = market[0]
    follow = rng.random((n_steps, n_assets)) < correlation
    for a in range(n_assets):
        for t in range(1, n_steps):
            states[t, a] = market[t] if follow[t, a] else states[t - 1, a]
    return states


def simulate_correlated_prices_euler(
    regimes: np.ndarray, s0: float, correlation: float, rng: np.random.Generator,
) -> np.ndarray:
    """Euler-Maruyama for n_assets paths sharing correlated return shocks (real crypto
    assets move together hour-to-hour, not just share volatility states) -- same GBM
    scheme as simulate_price_euler, generalized to correlated multi-asset shocks.
    `regimes` shape (n_steps, n_assets); returns prices, same shape."""
    n_steps, n_assets = regimes.shape
    corr = np.full((n_assets, n_assets), correlation)
    np.fill_diagonal(corr, 1.0)
    L = np.linalg.cholesky(corr)
    z = rng.standard_normal((n_steps - 1, n_assets)) @ L.T

    s = np.empty((n_steps, n_assets))
    s[0] = s0
    for t in range(1, n_steps):
        mu, sig = MU_STEP[regimes[t]], SIGMA_STEP[regimes[t]]
        s[t] = s[t - 1] * (1.0 + mu + sig * z[t - 1])
    return np.maximum(s, 1e-8)


def simulate_price_euler(regimes: np.ndarray, s0: float, rng: np.random.Generator) -> np.ndarray:
    """Euler-Maruyama, level-space: S_{t+1} = S_t*(1 + mu*dt + sigma*sqrt(dt)*Z)."""
    n = len(regimes)
    z = rng.standard_normal(n - 1)
    s = np.empty(n)
    s[0] = s0
    mu, sig = MU_STEP[regimes], SIGMA_STEP[regimes]
    for t in range(1, n):
        s[t] = s[t - 1] * (1.0 + mu[t] + sig[t] * z[t - 1])
    return np.maximum(s, 1e-8)


def simulate_price_milstein(regimes: np.ndarray, s0: float, rng: np.random.Generator) -> np.ndarray:
    """Milstein, level-space, GBM correction term: +0.5*sigma^2*S_t*(Z^2-1)."""
    n = len(regimes)
    z = rng.standard_normal(n - 1)
    s = np.empty(n)
    s[0] = s0
    mu, sig = MU_STEP[regimes], SIGMA_STEP[regimes]
    for t in range(1, n):
        s[t] = s[t - 1] * (1.0 + mu[t] + sig[t] * z[t - 1] + 0.5 * sig[t] ** 2 * (z[t - 1] ** 2 - 1.0))
    return np.maximum(s, 1e-8)


def convergence_order_check(regime: int = 3, horizon_hours: int = 240, n_paths: int = 200_000, seed: int = 42) -> dict:
    """Regime held FIXED (isolates discretization error from regime-switching noise).

    Compares Euler-Maruyama and Milstein against the closed-form lognormal solution's
    exact VARIANCE (not mean) at halving step sizes — the mean of this multiplicative
    scheme already matches the exact conditional mean at first order for both methods,
    so it can't distinguish them; Milstein's correction term specifically targets the
    diffusion (variance) term, so that's where its higher convergence order should
    actually show up. n_paths is large (200K) so Monte Carlo sampling noise in the
    variance estimate (~var*sqrt(2/n)) stays well below the expected discretization gap.
    """
    rng = np.random.default_rng(seed)
    mu_ann, sig_ann = ANNUAL_LOGRET_MEAN[regime] + 0.5 * ANNUAL_VOL[regime] ** 2, ANNUAL_VOL[regime]
    T = horizon_hours * DT
    s0 = 100.0

    exact_mean_log = np.log(s0) + (mu_ann - 0.5 * sig_ann ** 2) * T
    exact_std_log = sig_ann * np.sqrt(T)
    exact_variance = (np.exp(exact_std_log ** 2) - 1) * np.exp(2 * exact_mean_log + exact_std_log ** 2)
    mc_noise_floor = exact_variance * np.sqrt(2.0 / n_paths)  # ~std error of a variance estimate

    results = {}
    for n_substeps in [1, 2, 4, 8, 16]:
        n_steps = horizon_hours * n_substeps + 1
        dt_sub = DT / n_substeps
        mu_sub = (mu_ann - 0.5 * sig_ann ** 2) * dt_sub + 0.5 * (sig_ann * np.sqrt(dt_sub)) ** 2
        sig_sub = sig_ann * np.sqrt(dt_sub)

        s_euler = np.full(n_paths, s0)
        s_milstein = np.full(n_paths, s0)
        for t in range(n_steps - 1):
            zt = rng.standard_normal(n_paths)
            s_euler = s_euler * (1.0 + mu_sub + sig_sub * zt)
            s_milstein = s_milstein * (1.0 + mu_sub + sig_sub * zt + 0.5 * sig_sub ** 2 * (zt ** 2 - 1.0))

        results[n_substeps] = {
            "dt_hours": 1.0 / n_substeps,
            "euler_variance_error": float(abs(s_euler.var() - exact_variance)),
            "milstein_variance_error": float(abs(s_milstein.var() - exact_variance)),
        }
    results["exact_variance"] = float(exact_variance)
    results["mc_noise_floor"] = float(mc_noise_floor)
    return results


# --------------------------------------------------------------------- trinomial tree
def _tree_probabilities(mu_step: float, sig_step: float) -> tuple[float, float, float, float, float]:
    """CRR-style fixed jump sizes (u, d, m=1); solve for (p_u, p_m, p_d) via
    scipy.optimize to match target mean and variance of the per-step SIMPLE return,
    subject to summing to 1 and staying in [0,1] — a genuine small calibration problem,
    not a closed-form shortcut."""
    u = np.exp(sig_step * np.sqrt(3))
    d = 1.0 / u
    m = 1.0
    target_mean = mu_step  # approx: E[return] ~= mu_step for small step
    target_var = sig_step ** 2

    def loss(p):
        p_u, p_m = p
        p_d = 1.0 - p_u - p_m
        if p_d < 0 or p_u < 0 or p_m < 0:
            return 1e6
        mean = p_u * (u - 1) + p_m * (m - 1) + p_d * (d - 1)
        var = p_u * (u - 1) ** 2 + p_m * (m - 1) ** 2 + p_d * (d - 1) ** 2 - mean ** 2
        return (mean - target_mean) ** 2 + (var - target_var) ** 2

    res = minimize(loss, x0=[1 / 3, 1 / 3], method="Nelder-Mead", options={"xatol": 1e-10, "fatol": 1e-12})
    p_u, p_m = res.x
    p_d = 1.0 - p_u - p_m
    p_u, p_m, p_d = np.clip([p_u, p_m, p_d], 0, 1)
    total = p_u + p_m + p_d
    return u, m, d, res.fun, (p_u / total, p_m / total, p_d / total)


def calibrate_tree() -> dict[int, dict]:
    """Solve tree jump probabilities for every regime. Returns per-regime (u, m, d, probs, fit_loss)."""
    tree_params = {}
    for r in range(N_STATES):
        u, m, d, loss, (p_u, p_m, p_d) = _tree_probabilities(MU_STEP[r], SIGMA_STEP[r])
        tree_params[r] = {"u": u, "m": m, "d": d, "p_u": p_u, "p_m": p_m, "p_d": p_d, "calibration_loss": loss}
    return tree_params


def simulate_price_tree(regimes: np.ndarray, s0: float, tree_params: dict, rng: np.random.Generator) -> np.ndarray:
    n = len(regimes)
    s = np.empty(n)
    s[0] = s0
    for t in range(1, n):
        r = regimes[t]
        p = tree_params[r]
        jump = rng.choice([p["u"], p["m"], p["d"]], p=[p["p_u"], p["p_m"], p["p_d"]])
        s[t] = s[t - 1] * jump
    return np.maximum(s, 1e-8)
