"""Phase 1 validation of the 2026-08-19 engine fixes (regime/hmm.py: lengths=, no BIC
subsampling, best-of-N seeds + seed-sensitivity report) — see regime-layer audit.

Re-runs the FIXED engine against the exact same embeddings production's hmm_model.pkl
(n=4) was fit on, forcing n_states=4 so this is a controlled "did the fix change
anything it shouldn't, and does the new seed-sensitivity/lengths machinery actually
work end to end" check, not a fresh n_states search. Writes to fully isolated paths —
never touches production's regime_stream.parquet or regime/checkpoints/{hmm,pca}_model.pkl.

Reads data/processed/phase1_engine_test/{embeddings,embedding_timestamps,
embedding_asset_map} — a plain copy of data/processed/{...} made once for this check
(not regenerated by this script; see regime-layer audit conversation for the cp command).

Run: conda run -n marta python regime/run_hmm_engine_test.py
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import mlflow
import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from regime.hmm import run_hmm_pipeline

PROCESSED_DIR = "data/processed/phase1_engine_test"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--n-states", type=int, default=4,
        help="Forced n_states (default 4, matches production). Also used as a cheap "
             "stability side-check: try 2/3 to see whether low seed-sensitivity ARI is "
             "an 'n=4 has too many states for this separation' artifact or persists at "
             "coarser splits.",
    )
    args = parser.parse_args()

    checkpoint_dir = ROOT / "regime" / "checkpoints" / f"phase1_engine_test_n{args.n_states}"

    with open(ROOT / "configs" / "assets.yaml") as f:
        config = yaml.safe_load(f)
    config["data"]["processed_dir"] = PROCESSED_DIR

    embeddings_path = ROOT / PROCESSED_DIR / "embeddings.npy"
    if not embeddings_path.exists():
        print(f"ERROR: {embeddings_path} not found — copy data/processed/"
              f"{{embeddings.npy,embedding_timestamps.parquet,embedding_asset_map.parquet}} "
              f"into {PROCESSED_DIR}/ first.")
        sys.exit(1)

    print(f"processed_dir (isolated): {PROCESSED_DIR}")
    print(f"checkpoint_dir (isolated): {checkpoint_dir}")
    print(f"force_n_states: {args.n_states}")

    mlflow.set_tracking_uri(str(ROOT / "mlruns"))
    mlflow.set_experiment("marta_regime_hmm")
    with mlflow.start_run(run_name=f"phase1_engine_test_n{args.n_states}"):
        mlflow.log_param("experiment_tag", "phase1_engine_test")
        mlflow.log_param("purpose", "engine-fix regression check + n_states stability side-check")
        result = run_hmm_pipeline(
            config,
            force_n_states=args.n_states,
            checkpoint_dir=checkpoint_dir,
            pca_n_components=16,
            n_seeds=5,
        )
        regime_df = result["regime_df"]
        print(f"\nn_states={result['best_n']}")
        print(f"seed_sensitivity: {json.dumps(result['seed_sensitivity'], indent=2)}")
        print(f"Done: {len(regime_df):,} rows -> {checkpoint_dir}")


if __name__ == "__main__":
    main()
