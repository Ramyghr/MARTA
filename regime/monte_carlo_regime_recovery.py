"""The central exercise of the synthetic validation suite: run the ACTUAL feature
pipeline (pipeline/features.py + pipeline/normalize.py) and the ACTUAL HMM engine
(hmmlearn GaussianHMM, same config as regime/hmm.py's production fit — diag covariance,
n_states=6) on data generated by a process whose true regime label is known by
construction (regime/synthetic_regime_process.py, calibrated from the real crypto5_
multihorizon checkpoint). Every other test in this audit used real market data, where
the true regime is never known — this is the one place that gap gets closed.

For each of N_PATHS independent Monte Carlo realizations:
  1. Simulate a regime path + price path (Euler-Maruyama; a smaller sub-ensemble also
     uses the trinomial tree, to check results aren't an artifact of one generator).
  2. Synthesize OHLCV (close = simulated price; open = prior close; high/low = the
     open/close envelope; volume = a standard stylized-fact proxy, higher on larger
     |return|, since several production features depend on volume).
  3. Run through the real compute_features() -> normalize_features() pipeline (same
     720h window, same 14 columns).
  4. Fit a fresh GaussianHMM (diag cov, n_states=6, single seed for speed) and decode.
  5. Score recovery: Adjusted Rand Index, Normalized Mutual Information (both label-
     permutation-invariant, so HMM label-switching doesn't matter), and Hungarian-
     matched classification accuracy (scipy.optimize.linear_sum_assignment on the
     confusion matrix — the most interpretable number: % of hours correctly classified
     after optimal relabeling).

Run: conda run -n marta python regime/monte_carlo_regime_recovery.py
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from hmmlearn.hmm import GaussianHMM
from scipy.optimize import linear_sum_assignment
from sklearn.metrics import adjusted_rand_score, normalized_mutual_info_score

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import yaml

from pipeline.features import compute_features
from pipeline.normalize import normalize_features_multihorizon
from regime.synthetic_regime_process import (
    N_STATES,
    calibrate_tree,
    simulate_price_euler,
    simulate_price_tree,
    simulate_regime_path,
)
from utils.logger import logger

N_STEPS = 8760  # 1 year of hourly data per synthetic path
N_PATHS_EULER = 20
N_PATHS_TREE = 10


def _synthesize_ohlcv(price: np.ndarray, regimes: np.ndarray, rng: np.random.Generator) -> pd.DataFrame:
    """close = simulated price. open = prior close (standard single-price-process
    convention). high/low = the open/close envelope (no intra-bar granularity modeled).
    volume = base * (1 + k*|return|) * lognormal noise -- the standard stylized fact
    that volume rises with absolute price moves, needed since several production
    features (obv_raw, vol_zscore) depend on it."""
    n = len(price)
    close = price
    open_ = np.empty(n)
    open_[0] = close[0]
    open_[1:] = close[:-1]
    high = np.maximum(open_, close)
    low = np.minimum(open_, close)
    ret = np.diff(np.log(close), prepend=np.log(close[0]))
    base_volume = 1_000_000.0
    volume = base_volume * (1.0 + 15.0 * np.abs(ret)) * rng.lognormal(mean=0.0, sigma=0.25, size=n)

    idx = pd.date_range("2020-01-01", periods=n, freq="1h", tz="UTC")
    return pd.DataFrame({"open": open_, "high": high, "low": low, "close": close, "volume": volume}, index=idx)


def _fit_and_recover(features_df: pd.DataFrame, true_regimes: np.ndarray, seed: int) -> dict:
    # all 22 columns (14 base + 8 multi-horizon) -- matches the actual calibration
    # source (crypto5_multihorizon), not the weaker 14-col set.
    X = features_df.to_numpy(dtype=np.float64)
    model = GaussianHMM(n_components=N_STATES, covariance_type="diag", n_iter=100, random_state=seed, tol=1e-4)
    model.fit(X)
    recovered = model.predict(X)

    ari = adjusted_rand_score(true_regimes, recovered)
    nmi = normalized_mutual_info_score(true_regimes, recovered)

    # Hungarian-matched accuracy: optimal relabeling of recovered -> true via the
    # confusion matrix, then plain classification accuracy under that best matching.
    conf = np.zeros((N_STATES, N_STATES), dtype=int)
    for t, r in zip(true_regimes, recovered):
        conf[int(t), int(r)] += 1
    row_ind, col_ind = linear_sum_assignment(-conf)  # maximize matched count
    matched_correct = conf[row_ind, col_ind].sum()
    accuracy = matched_correct / len(true_regimes)

    return {
        "ari": float(ari),
        "nmi": float(nmi),
        "hungarian_accuracy": float(accuracy),
        "converged": bool(model.monitor_.converged),
        "n_recovered_states_used": int(len(np.unique(recovered))),
    }


def _fit_and_recover_best_of_n_seeds(features_df: pd.DataFrame, true_regimes: np.ndarray, seed_base: int, n_seeds: int = 5) -> dict:
    """Matches the ACTUAL production fitting procedure (regime/hmm.py's
    _fit_multiseed) rather than the single-seed test above -- fits n_seeds
    independent models, keeps the highest-training-log-likelihood one. Tests whether
    recovery improves once the real methodology (not a weaker single-seed proxy) is used."""
    X = features_df.to_numpy(dtype=np.float64)
    best_model, best_ll = None, -np.inf
    for i in range(n_seeds):
        model = GaussianHMM(n_components=N_STATES, covariance_type="diag", n_iter=100, random_state=seed_base + i, tol=1e-4)
        model.fit(X)
        ll = model.score(X)
        if ll > best_ll:
            best_ll, best_model = ll, model
    recovered = best_model.predict(X)

    conf = np.zeros((N_STATES, N_STATES), dtype=int)
    for t, r in zip(true_regimes, recovered):
        conf[int(t), int(r)] += 1
    row_ind, col_ind = linear_sum_assignment(-conf)
    accuracy = conf[row_ind, col_ind].sum() / len(true_regimes)

    return {
        "ari": float(adjusted_rand_score(true_regimes, recovered)),
        "nmi": float(normalized_mutual_info_score(true_regimes, recovered)),
        "hungarian_accuracy": float(accuracy),
        "n_seeds": n_seeds,
    }


def run_ensemble(
    generator: str, n_paths: int, seed_base: int = 100, n_steps: int = N_STEPS, multiseed: bool = False,
) -> list[dict]:
    tree_params = calibrate_tree() if generator == "tree" else None
    results = []
    for i in range(n_paths):
        t0 = time.time()
        rng = np.random.default_rng(seed_base + i)
        regimes = simulate_regime_path(n_steps, rng)

        if generator == "euler":
            price = simulate_price_euler(regimes, 100.0, rng)
        elif generator == "tree":
            price = simulate_price_tree(regimes, 100.0, tree_params, rng)
        else:
            raise ValueError(generator)

        ohlcv = _synthesize_ohlcv(price, regimes, rng)
        feats18 = compute_features(ohlcv.copy(), f"SYNTH_{generator}_{i}")
        with open(ROOT / "configs" / "assets.yaml") as f:
            config = yaml.safe_load(f)
        feats22 = normalize_features_multihorizon(feats18, config)

        # trim true regimes to the surviving (post-warmup-dropna) index
        true_trimmed = pd.Series(regimes, index=ohlcv.index).reindex(feats22.index).to_numpy()

        if multiseed:
            rec = _fit_and_recover_best_of_n_seeds(feats22, true_trimmed, seed_base=1000 * (seed_base + i))
        else:
            rec = _fit_and_recover(feats22, true_trimmed, seed=seed_base + i)
        rec["path"] = i
        rec["generator"] = generator
        rec["elapsed_s"] = round(time.time() - t0, 1)
        results.append(rec)
        logger.info(
            f"[{generator} {i + 1}/{n_paths}] ARI={rec['ari']:.3f}  NMI={rec['nmi']:.3f}  "
            f"hungarian_acc={rec['hungarian_accuracy']:.3f}  ({rec['elapsed_s']:.1f}s)"
        )
        stray = ROOT / "data" / "processed" / f"SYNTH_{generator}_{i}_features.parquet"
        stray.unlink(missing_ok=True)  # compute_features() always writes this; synthetic runs shouldn't litter data/processed
    return results


N_PATHS_LONGHORIZON = 5
LONGHORIZON_STEPS = N_STEPS * 3  # ~3 years/path -- tests whether 1-year recovery is a
# sample-size artifact rather than a methodology limitation (real production's
# crypto5_multihorizon was fit on ~247K rows, ~28 asset-years -- far more than 1 path-year)


def run_pooled_ensemble(n_assets: int, n_trials: int, n_steps: int = N_STEPS, seed_base: int = 2000) -> list[dict]:
    """Tests the actual hypothesis raised by the flat single-asset recovery results:
    is production's real ARI=1.000 driven by pooling multiple INDEPENDENT realizations
    of the same process (more independent samples for EM to estimate shared parameters
    from), not by more calendar time? Each trial simulates n_assets independent 1-year
    paths from the SAME calibrated process, pools them (mirroring
    regime/build_crypto5_features.py's block-per-asset convention) into ONE HMM fit
    using lengths= (so multi-asset sequences are modeled as independent chains, per the
    Phase-1 engine fix -- not the bug that motivated it in the first place)."""
    results = []
    for trial in range(n_trials):
        t0 = time.time()
        all_feats, all_true, lengths = [], [], []
        for a in range(n_assets):
            rng = np.random.default_rng(seed_base + trial * 100 + a)
            regimes = simulate_regime_path(n_steps, rng)
            price = simulate_price_euler(regimes, 100.0, rng)
            ohlcv = _synthesize_ohlcv(price, regimes, rng)
            feats18 = compute_features(ohlcv.copy(), f"SYNTH_pool_{trial}_{a}")
            with open(ROOT / "configs" / "assets.yaml") as f:
                config = yaml.safe_load(f)
            feats22 = normalize_features_multihorizon(feats18, config)
            true_trimmed = pd.Series(regimes, index=ohlcv.index).reindex(feats22.index).to_numpy()

            all_feats.append(feats22.to_numpy(dtype=np.float64))
            all_true.append(true_trimmed)
            lengths.append(len(feats22))
            (ROOT / "data" / "processed" / f"SYNTH_pool_{trial}_{a}_features.parquet").unlink(missing_ok=True)

        X = np.concatenate(all_feats, axis=0)
        true_pooled = np.concatenate(all_true, axis=0)
        lengths = np.array(lengths)

        model = GaussianHMM(n_components=N_STATES, covariance_type="diag", n_iter=100, random_state=seed_base + trial, tol=1e-4)
        model.fit(X, lengths=lengths)
        recovered = model.predict(X, lengths=lengths)

        conf = np.zeros((N_STATES, N_STATES), dtype=int)
        for t, r in zip(true_pooled, recovered):
            conf[int(t), int(r)] += 1
        row_ind, col_ind = linear_sum_assignment(-conf)
        accuracy = conf[row_ind, col_ind].sum() / len(true_pooled)

        rec = {
            "trial": trial,
            "n_assets": n_assets,
            "ari": float(adjusted_rand_score(true_pooled, recovered)),
            "nmi": float(normalized_mutual_info_score(true_pooled, recovered)),
            "hungarian_accuracy": float(accuracy),
            "elapsed_s": round(time.time() - t0, 1),
        }
        results.append(rec)
        logger.info(
            f"[pooled n_assets={n_assets} trial {trial + 1}/{n_trials}] ARI={rec['ari']:.3f}  "
            f"hungarian_acc={rec['hungarian_accuracy']:.3f}  ({rec['elapsed_s']:.1f}s)"
        )
    return results


def run_pooled_correlated_ensemble(
    n_assets: int, n_trials: int, correlation: float = 0.7, n_steps: int = N_STEPS, seed_base: int = 3000,
) -> list[dict]:
    """H1 (2026-08-20): does real cross-asset CORRELATION -- not just more independent
    rows -- explain why production's real ARI=1.000 wasn't reproduced by pooling
    independent synthetic assets (run_pooled_ensemble, ARI stayed ~0.16)? Same pooled-
    fit design, but the n_assets regime paths and return shocks are generated with a
    Gaussian-copula correlation of `correlation` (default 0.7, a representative crypto
    pairwise correlation) via simulate_correlated_regime_paths /
    simulate_correlated_prices_euler, instead of independent draws."""
    from regime.synthetic_regime_process import simulate_correlated_prices_euler, simulate_correlated_regime_paths

    results = []
    for trial in range(n_trials):
        t0 = time.time()
        rng = np.random.default_rng(seed_base + trial)
        regimes_2d = simulate_correlated_regime_paths(n_assets, n_steps, correlation, rng)  # (n_steps, n_assets)
        prices_2d = simulate_correlated_prices_euler(regimes_2d, 100.0, correlation, rng)

        all_feats, all_true, lengths = [], [], []
        for a in range(n_assets):
            regimes = regimes_2d[:, a]
            price = prices_2d[:, a]
            ohlcv = _synthesize_ohlcv(price, regimes, rng)
            feats18 = compute_features(ohlcv.copy(), f"SYNTH_corr_{trial}_{a}")
            with open(ROOT / "configs" / "assets.yaml") as f:
                config = yaml.safe_load(f)
            feats22 = normalize_features_multihorizon(feats18, config)
            true_trimmed = pd.Series(regimes, index=ohlcv.index).reindex(feats22.index).to_numpy()

            all_feats.append(feats22.to_numpy(dtype=np.float64))
            all_true.append(true_trimmed)
            lengths.append(len(feats22))
            (ROOT / "data" / "processed" / f"SYNTH_corr_{trial}_{a}_features.parquet").unlink(missing_ok=True)

        X = np.concatenate(all_feats, axis=0)
        true_pooled = np.concatenate(all_true, axis=0)
        lengths_arr = np.array(lengths)

        model = GaussianHMM(n_components=N_STATES, covariance_type="diag", n_iter=100, random_state=seed_base + trial, tol=1e-4)
        model.fit(X, lengths=lengths_arr)
        recovered = model.predict(X, lengths=lengths_arr)

        conf = np.zeros((N_STATES, N_STATES), dtype=int)
        for t, r in zip(true_pooled, recovered):
            conf[int(t), int(r)] += 1
        row_ind, col_ind = linear_sum_assignment(-conf)
        accuracy = conf[row_ind, col_ind].sum() / len(true_pooled)

        # simultaneous-regime-share sanity check: how often are all n_assets actually
        # in the same true regime at once, at this correlation level -- confirms the
        # copula is producing meaningfully correlated (not just marginally-identical)
        # regime paths.
        same_regime_frac = float((regimes_2d == regimes_2d[:, [0]]).all(axis=1).mean())

        rec = {
            "trial": trial, "n_assets": n_assets, "correlation": correlation,
            "ari": float(adjusted_rand_score(true_pooled, recovered)),
            "nmi": float(normalized_mutual_info_score(true_pooled, recovered)),
            "hungarian_accuracy": float(accuracy),
            "simultaneous_same_regime_frac": same_regime_frac,
            "elapsed_s": round(time.time() - t0, 1),
        }
        results.append(rec)
        logger.info(
            f"[correlated n_assets={n_assets} rho={correlation} trial {trial + 1}/{n_trials}] "
            f"ARI={rec['ari']:.3f}  hungarian_acc={rec['hungarian_accuracy']:.3f}  "
            f"simultaneous_same_regime={same_regime_frac:.3f}  ({rec['elapsed_s']:.1f}s)"
        )
    return results


def main() -> None:
    logger.info(f"=== Monte Carlo regime recovery: {N_PATHS_EULER} Euler paths, {N_PATHS_TREE} tree paths, "
                f"{N_STEPS:,} hours/path ===")
    euler_results = run_ensemble("euler", N_PATHS_EULER)
    tree_results = run_ensemble("tree", N_PATHS_TREE)

    logger.info(f"=== Long-horizon comparison: {N_PATHS_LONGHORIZON} Euler paths, "
                f"{LONGHORIZON_STEPS:,} hours/path (~3 years) — is 1yr recovery a sample-size artifact? ===")
    longhorizon_results = run_ensemble("euler", N_PATHS_LONGHORIZON, seed_base=500, n_steps=LONGHORIZON_STEPS)

    logger.info("=== Multi-seed comparison: 5 Euler paths, 1yr, best-of-5-seeds "
                "(matches the ACTUAL production fitting procedure) ===")
    multiseed_results = run_ensemble("euler", 5, seed_base=700, multiseed=True)

    all_results = {
        "euler_1yr": euler_results, "tree_1yr": tree_results,
        "euler_3yr": longhorizon_results, "euler_1yr_bestof5seeds": multiseed_results,
    }
    for gen, results in all_results.items():
        aris = [r["ari"] for r in results]
        nmis = [r["nmi"] for r in results]
        accs = [r["hungarian_accuracy"] for r in results]
        logger.success(
            f"[{gen}] ARI: mean={np.mean(aris):.3f} median={np.median(aris):.3f} "
            f"std={np.std(aris):.3f} min={np.min(aris):.3f} max={np.max(aris):.3f} | "
            f"hungarian_acc: mean={np.mean(accs):.3f} median={np.median(accs):.3f}"
        )

    out_path = ROOT / "data" / "results" / "monte_carlo_regime_recovery.json"
    out_path.write_text(json.dumps(all_results, indent=2, default=float))
    logger.success(f"Saved -> {out_path}")


if __name__ == "__main__":
    main()
